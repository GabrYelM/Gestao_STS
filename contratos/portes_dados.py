def carregar_portes_padrao(conn, sobrescrever=False):
    """Carrega os procedimentos padrao da Portaria AEA no banco de dados."""
    if sobrescrever:
        conn.execute("DELETE FROM procedimento_portes")
    
    total_inseridos = 0
    for p in PROCEDIMENTOS_AEA_PADRAO:
        conn.execute("""
            INSERT INTO procedimento_portes (codigo, codigo_formatado, nome, instrumento, porte, grupo, ativo)
            VALUES (?, ?, ?, ?, ?, ?, 1)
            ON CONFLICT(codigo) DO UPDATE SET
                codigo_formatado = excluded.codigo_formatado,
                nome = CASE WHEN procedimento_portes.nome IS NULL OR procedimento_portes.nome = '' THEN excluded.nome ELSE procedimento_portes.nome END,
                instrumento = CASE WHEN ? THEN excluded.instrumento ELSE procedimento_portes.instrumento END,
                porte = CASE WHEN ? THEN excluded.porte ELSE procedimento_portes.porte END,
                grupo = CASE WHEN ? THEN excluded.grupo ELSE procedimento_portes.grupo END,
                atualizado_em = CURRENT_TIMESTAMP
        """, (p['codigo'], p['codigo_formatado'], p['nome'], p['instrumento'], p['porte'], p['grupo'], 1 if sobrescrever else 0, 1 if sobrescrever else 0, 1 if sobrescrever else 0))
        total_inseridos += 1
    return total_inseridos
